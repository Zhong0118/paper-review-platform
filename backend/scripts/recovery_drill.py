def _test_url() -> str:
    url = make_url(get_settings().database_url)
    if url.host not in {"127.0.0.1", "localhost"} or url.port != 5433 or url.database != "paper_review_test":
        raise ValueError("recovery requires 127.0.0.1:5433/paper_review_test")
    return url.render_as_string(hide_password=False)


@dataclass
class OwnedResources:
    schema: str
    schema_oid: int | None
    storage_root: Path
    storage_dev: int | None
    storage_inode: int | None
    owner_role: str
    business_role: str
    auth_role: str
    role_oids: dict[str, int]
    database_url: str = field(repr=False)

    @classmethod
    def capture(cls, runtime) -> OwnedResources:
        database_url = _test_url()
        if not re.fullmatch(r"test_[0-9a-f]{32}", runtime.schema):
            raise ValueError("recovery schema was not generated by the test lifecycle")
        root = runtime.storage_root
        info = root.lstat()
        if root.is_symlink() or not root.is_dir() or not root.name.startswith(
            f"paper-review-acceptance-{runtime.schema}-"
        ):
            raise ValueError("recovery storage was not generated by the test lifecycle")
        role_urls = [make_url(os.environ[key]) for key in (
            "MIGRATION_DATABASE_URL", "BUSINESS_DATABASE_URL", "AUTH_DATABASE_URL"
        )]
        if any(url.host not in {"127.0.0.1", "localhost"} or url.port != 5433
               or url.database != "paper_review_test" for url in role_urls):
            raise ValueError("role database must be local 5433/paper_review_test")
        role_names = [url.username for url in role_urls]
        if None in role_names or len(set(role_names)) != 3:
            raise ValueError("recovery requires three distinct isolated roles")
        engine = create_engine(database_url.replace("+asyncpg", "+psycopg"))
        try:
            with engine.connect() as conn:
                row = conn.execute(text("""
                    SELECT n.oid, r.rolname FROM pg_namespace n
                    JOIN pg_roles r ON r.oid=n.nspowner WHERE n.nspname=:schema
                """), {"schema": runtime.schema}).one()
                role_rows = conn.execute(text(
                    "SELECT rolname, oid, rolsuper, rolbypassrls, rolcreaterole "
                    "FROM pg_roles WHERE rolname=ANY(:names)"
                ), {"names": role_names}).all()
                roles = {name: oid for name, oid, *_flags in role_rows}
        finally:
            engine.dispose()
        if row[1] != role_names[0] or set(roles) != set(role_names):
            raise ValueError("recovery role ownership mismatch")
        if any(superuser or bypassrls or createrole for _name, _oid, superuser, bypassrls, createrole in role_rows):
            raise ValueError("recovery roles cannot have SUPERUSER, BYPASSRLS or CREATEROLE")
        return cls(runtime.schema, row[0], root, info.st_dev, info.st_ino,
                   role_names[0], role_names[1], role_names[2], roles, database_url)

    def assert_cleanup_stage(self, stage: str) -> None:
        if stage not in {"schema", "roles", "storage"}:
            raise ValueError("unknown cleanup stage")
        _test_url()
        if self.storage_inode is None:
            if self.storage_root.exists() or self.storage_root.is_symlink():
                raise ValueError("storage ownership changed")
        else:
            if self.storage_root.is_symlink() or not self.storage_root.is_dir():
                raise ValueError("storage ownership changed")
            info = self.storage_root.lstat()
            if (info.st_dev, info.st_ino) != (self.storage_dev, self.storage_inode):
                raise ValueError("storage ownership changed")
        engine = create_engine(self.database_url.replace("+asyncpg", "+psycopg"))
        try:
            with engine.connect() as conn:
                actual_schema = conn.execute(text(
                    "SELECT oid, nspowner FROM pg_namespace WHERE nspname=:schema"
                ), {"schema": self.schema}).one_or_none()
                if stage == "schema" and actual_schema is not None:
                    _assert_schema_dependencies(conn, self.schema_oid)
                role_rows = conn.execute(text(
                    "SELECT rolname, oid, rolsuper, rolbypassrls, rolcreaterole "
                    "FROM pg_roles WHERE rolname=ANY(:names)"
                ), {"names": list(self.role_oids)}).all()
                actual_roles = {name: oid for name, oid, *_flags in role_rows}
        finally:
            engine.dispose()
        expected_schema = (self.schema_oid, self.role_oids[self.owner_role]) if stage == "schema" and self.schema_oid is not None else None
        if actual_schema != expected_schema:
            raise ValueError("schema ownership changed")
        expected_roles = self.role_oids if stage != "storage" else {}
        if actual_roles != expected_roles:
            raise ValueError("role ownership changed")
        if any(superuser or bypassrls or createrole for _name, _oid, superuser, bypassrls, createrole in role_rows):
            raise ValueError("recovery role gained SUPERUSER, BYPASSRLS or CREATEROLE")


def _assert_schema_dependencies(conn, schema_oid: int) -> None:
    """Reject dependencies outside this schema's objects and their internal children.

    pg_rewrite/constraints/TOAST have no direct namespace membership of their own;
    following internal/auto ownership edges includes them without admitting normal
    dependencies on another user's objects. Run with writes stopped, like the drill.
    """
    external = conn.execute(text("""
        WITH RECURSIVE owned(classid, objid) AS (
            SELECT 'pg_namespace'::regclass::oid, CAST(:schema AS oid)
            UNION
            SELECT d.classid, d.objid FROM pg_depend d JOIN owned o
              ON d.refclassid=o.classid AND d.refobjid=o.objid
            WHERE (o.classid='pg_namespace'::regclass AND o.objid=:schema)
               OR d.deptype IN ('i','a')
        )
        SELECT 1 FROM pg_depend d
        LEFT JOIN owned source ON source.classid=d.classid AND source.objid=d.objid
        LEFT JOIN owned target ON target.classid=d.refclassid AND target.objid=d.refobjid
        WHERE (target.objid IS NOT NULL AND source.objid IS NULL)
           OR (source.objid IS NOT NULL AND target.objid IS NULL AND NOT (
               d.refobjid < 16384
               AND (d.refclassid <> 'pg_namespace'::regclass OR d.refobjid IN (11,99))
               AND COALESCE((pg_identify_object(d.refclassid,d.refobjid,0)).schema, 'pg_catalog')='pg_catalog'
           ))
        LIMIT 1
    """), {"schema": schema_oid}).first()
    if external is not None:
        raise ValueError("external schema dependency; refusing backup or cleanup")


def _digest(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


class DockerPostgres:
    """Use only the existing, verified PostgreSQL 16 container for binary archives."""

    def __init__(self, database_url: str):
        url = make_url(database_url)
        if url.host not in {"127.0.0.1", "localhost"} or url.port != 5433 or url.database != "paper_review_test":
            raise ValueError("docker transport requires local 5433/paper_review_test")
        if not url.username or url.password is None:
            raise ValueError("docker transport requires a database login")
        self.database_url = database_url
        self.username = url.username
        self.password = url.password
        self.container_id = ""
        self.pgpass_path = ""
        self.pgpass_inode = ""

    def _inspect(self) -> None:
        result = subprocess.run(
            ["docker", "inspect", "paper-review-postgres"], capture_output=True, text=True, check=True
        )
        item = json.loads(result.stdout)[0]
        mapping = item["HostConfig"]["PortBindings"].get("5432/tcp")
        if (item["Config"]["Image"] != "postgres:16-alpine" or
                mapping != [{"HostIp": "127.0.0.1", "HostPort": "5433"}] or
                not item["State"]["Running"]):
            raise ValueError("database container identity or port mapping changed")
        if self.container_id and self.container_id != item["Id"]:
            raise ValueError("database container was replaced")
        self.container_id = item["Id"]

    def __enter__(self) -> DockerPostgres:
        self._inspect()
        versions = {}
        for program in ("pg_dump", "pg_restore"):
            version = subprocess.run(
                ["docker", "exec", self.container_id, program, "--version"],
                capture_output=True, text=True, check=True,
            ).stdout.strip()
            match = re.fullmatch(rf"{program} \(PostgreSQL\) (\d+)\.\d+", version)
            if match is None:
                raise ValueError(f"{program} version is unavailable")
            versions[program] = int(match.group(1))
        engine = create_engine(self.database_url.replace("+asyncpg", "+psycopg"))
        try:
            with engine.connect() as conn:
                server_major = int(conn.execute(text("SHOW server_version_num")).scalar_one()) // 10000
        finally:
            engine.dispose()
        if any(major < server_major for major in versions.values()):
            raise ValueError("pg_dump and pg_restore must not be older than the server")
        created = subprocess.run(
            ["docker", "exec", self.container_id, "mktemp", "/tmp/paper-review-recovery-XXXXXXXX"],
            capture_output=True, text=True, check=True,
        )
        self.pgpass_path = created.stdout.strip()
        try:
            escaped = self.password.replace("\\", "\\\\").replace(":", "\\:")
            line = f"127.0.0.1:5432:paper_review_test:{self.username}:{escaped}\n".encode()
            subprocess.run(
                ["docker", "exec", "-i", self.container_id, "sh", "-c", 'cat > "$1"', "sh", self.pgpass_path],
                input=line, stdout=subprocess.DEVNULL, stderr=subprocess.PIPE, check=True,
            )
            self.pgpass_inode = subprocess.run(
                ["docker", "exec", self.container_id, "stat", "-c", "%d:%i:%a", self.pgpass_path],
                capture_output=True, text=True, check=True,
            ).stdout.strip()
            if not self.pgpass_inode.endswith(":600"):
                raise ValueError("container PGPASSFILE is not mode 0600")
            return self
        except Exception:
            self.__exit__(None, None, None)
            raise

    def __exit__(self, *_exc) -> None:
        if not self.pgpass_path:
            return
        self._inspect()
        actual = subprocess.run(
            ["docker", "exec", self.container_id, "stat", "-c", "%d:%i:%a", self.pgpass_path],
            capture_output=True, text=True,
        )
        if actual.returncode != 0 or actual.stdout.strip() != self.pgpass_inode:
            raise ValueError("container PGPASSFILE ownership changed; refusing cleanup")
        subprocess.run(["docker", "exec", self.container_id, "rm", "--", self.pgpass_path],
                       capture_output=True, check=True)
        self.pgpass_path = ""

    def _command(self, program: str, extra: list[str]) -> list[str]:
        self._inspect()
        return ["docker", "exec", "-i", "-e", f"PGPASSFILE={self.pgpass_path}", self.container_id,
                program, "--host=127.0.0.1", "--port=5432", f"--username={self.username}",
                "--no-password", "--dbname=paper_review_test", *extra]

    def dump(self, schema: str, target: Path) -> None:
        fd = os.open(target, os.O_CREAT | os.O_EXCL | os.O_WRONLY, 0o600)
        with os.fdopen(fd, "wb") as output:
            result = subprocess.run(self._command("pg_dump", ["--format=custom", f"--schema={schema}"]),
                                    stdout=output, stderr=subprocess.PIPE)
        if result.returncode:
            raise RuntimeError(f"pg_dump failed (exit {result.returncode})")

    def list_archive(self, archive: Path) -> str:
        with archive.open("rb") as source:
            result = subprocess.run(["docker", "exec", "-i", self.container_id, "pg_restore", "--list"],
                                    stdin=source, stdout=subprocess.PIPE, stderr=subprocess.PIPE)
        if result.returncode:
            raise ValueError("pg_restore could not read archive")
        return result.stdout.decode(errors="replace")

    def restore(self, archive: Path) -> None:
        with archive.open("rb") as source:
            result = subprocess.run(
                self._command("pg_restore", ["--single-transaction", "--exit-on-error"]),
                stdin=source, stdout=subprocess.DEVNULL, stderr=subprocess.PIPE,
            )
        if result.returncode:
            raise RuntimeError(f"pg_restore failed (exit {result.returncode})")


def _database_snapshot(owned: OwnedResources) -> dict:
    engine = create_engine(owned.database_url.replace("+asyncpg", "+psycopg"))
    try:
        with engine.connect() as conn:
            relations = conn.execute(text("""
                SELECT c.relname, r.rolname, c.relrowsecurity, c.relforcerowsecurity
                FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace
                JOIN pg_roles r ON r.oid=c.relowner
                WHERE n.nspname=:schema AND c.relkind IN ('r','p') ORDER BY c.relname
            """), {"schema": owned.schema}).all()
            tables = {}
            for name, owner, rls, force in relations:
                if not re.fullmatch(r"[a-z_][a-z0-9_]*", name):
                    raise ValueError("unexpected relation name")
                relation = f'"{owned.schema}"."{name}"'
                count = conn.execute(text(f'SELECT count(*) FROM {relation}')).scalar_one()
                grants = {}
                for role in owned.role_oids:
                    privileges = conn.execute(text("""
                        SELECT has_table_privilege(:role,:relation,'SELECT'),
                               has_table_privilege(:role,:relation,'INSERT'),
                               has_table_privilege(:role,:relation,'UPDATE'),
                               has_table_privilege(:role,:relation,'DELETE')
                    """), {"role": role, "relation": relation}).one()
                    grants[role] = dict(zip(("select", "insert", "update", "delete"), privileges))
                    if name == "users":
                        grants[role]["password_hash_select"] = conn.execute(text("""
                            SELECT has_column_privilege(:role,:relation,'password_hash','SELECT')
                        """), {"role": role, "relation": relation}).scalar_one()
                tables[name] = {"count": count, "owner": owner, "rls": rls,
                                "force_rls": force, "grants": grants}
            for name in ('review_result_versions', 'result_publications', 'review_correction_requests', 'review_correction_notes', 'review_result_revisions', 'tenant_sensitive_terms', 'anonymization_checks'):
                rows = conn.execute(text(f'SELECT to_jsonb(t) FROM "{owned.schema}"."{name}" t ORDER BY id')).scalars().all()
                tables[name]['content_sha256'] = hashlib.sha256(
                    json.dumps(rows, sort_keys=True, ensure_ascii=False).encode()).hexdigest()
            revision = conn.execute(text(f'SELECT version_num FROM "{owned.schema}".alembic_version')).scalar_one()
            file_rows = conn.execute(text(f'''
                SELECT id,storage_key,size_bytes,sha256,completed_at
                FROM "{owned.schema}".file_objects ORDER BY id
            ''')).all()
            summaries = conn.execute(text(f'''
                SELECT id,total,rule_snapshot FROM "{owned.schema}".result_summaries ORDER BY id
            ''')).all()
            thesis_ids = [str(value) for value in conn.execute(text(
                f'SELECT id FROM "{owned.schema}".theses ORDER BY id'
            )).scalars()]
            task_ids = [str(value) for value in conn.execute(text(
                f'SELECT id FROM "{owned.schema}".expert_tasks ORDER BY id'
            )).scalars()]
            publications = [{"id": str(item_id), "published_at": published_at.isoformat()}
                            for item_id, published_at in conn.execute(text(
                                f'SELECT id,published_at FROM "{owned.schema}".result_publications ORDER BY id'
                            ))]
    finally:
        engine.dispose()
    if ("alembic_version" not in tables or len(tables) - 1 != 34 or
            any(not value["rls"] or not value["force_rls"] or value["owner"] != owned.owner_role
                for name, value in tables.items() if name != "alembic_version")):
        raise ValueError("expected 34 FORCE RLS business tables")
    if tables["users"]["grants"][owned.business_role]["password_hash_select"]:
        raise ValueError("business role can read password hashes")
    return {"tables": tables, "revision": revision, "file_rows": file_rows,
            "summaries": [{"id": str(i), "total": total, "rule_snapshot": rule}
                          for i, total, rule in summaries],
            "references": {"thesis_ids": thesis_ids, "task_ids": task_ids,
                           "publication_ids": [item["id"] for item in publications],
                           "publications": publications}}


def _source_files(owned: OwnedResources, rows: list) -> list[dict]:
    root = owned.storage_root
    physical: dict[str, Path] = {}
    for item in root.rglob("*"):
        if item.is_symlink():
            raise ValueError("storage contains a symbolic link")
        if item.is_file():
            physical[item.relative_to(root).as_posix()] = item
    records = {}
    for file_id, key, size, sha, completed_at in rows:
        path = Path(key)
        if not path.is_absolute() or ".." in path.parts or path.is_symlink():
            raise ValueError("file storage key is not normalized")
        try:
            rel = path.resolve(strict=False).relative_to(root.resolve()).as_posix()
        except ValueError as exc:
            raise ValueError("file storage key escapes owned storage") from exc
        if rel in records:
            raise ValueError("duplicate file storage key")
        if completed_at is not None and rel not in physical:
            raise ValueError("completed file is missing")
        records[rel] = {"file_id": str(file_id), "completed": completed_at is not None,
                        "database_size": size, "database_sha256": sha}
    files = []
    for rel, path in sorted(physical.items()):
        size = path.stat().st_size
        sha = _digest(path)
        record = records.get(rel, {})
        if record.get("completed") and (size != record["database_size"] or sha != record["database_sha256"]):
            raise ValueError("completed file differs from database record")
        files.append({"path": rel, "size": size, "sha256": sha,
                      "file_id": record.get("file_id"), "completed": record.get("completed", False)})
    return files


def _check_archive_dir(owned: OwnedResources, archive_dir: Path) -> None:
    if archive_dir.is_symlink() or not archive_dir.is_dir():
        raise ValueError("archive directory must be an owned directory")
    if archive_dir.resolve() == owned.storage_root.resolve() or owned.storage_root.resolve() in archive_dir.resolve().parents:
        raise ValueError("archive directory is inside source storage")
    if stat.S_IMODE(archive_dir.stat().st_mode) != 0o700:
        raise ValueError("archive directory must be mode 0700")


def backup_owned_resources(owned: OwnedResources, archive_dir: Path) -> dict:
    owned.assert_cleanup_stage("schema")
    _check_archive_dir(owned, archive_dir)
    if any(archive_dir.iterdir()):
        raise ValueError("archive directory must start empty")
    snapshot = _database_snapshot(owned)
    files = _source_files(owned, snapshot["file_rows"])
    with DockerPostgres(owned.database_url) as client:
        archive = archive_dir / "database.dump"
        client.dump(owned.schema, archive)
        toc = client.list_archive(archive)
    if owned.schema not in toc:
        raise ValueError("archive TOC lacks owned schema")
    file_dir = archive_dir / "files"
    file_dir.mkdir(mode=0o700)
    for item in files:
        source = owned.storage_root / item["path"]
        target = file_dir / item["path"]
        target.parent.mkdir(parents=True, exist_ok=True, mode=0o700)
        fd = os.open(target, os.O_CREAT | os.O_EXCL | os.O_WRONLY, 0o600)
        with source.open("rb") as input_stream, os.fdopen(fd, "wb") as output_stream:
            shutil.copyfileobj(input_stream, output_stream)
        if _digest(target) != item["sha256"]:
            raise ValueError("file copy hash differs from source")
    manifest = {"format_version": 1, "resource_id": owned.schema,
                "database": {"host": "127.0.0.1", "port": 5433, "name": "paper_review_test"},
                "schema_oid": owned.schema_oid, "roles": list(owned.role_oids),
                "storage_root": str(owned.storage_root),
                "backup_at": datetime.now(timezone.utc).isoformat(),
                "revision": snapshot["revision"], "tables": snapshot["tables"],
                "summaries": snapshot["summaries"], "references": snapshot["references"],
                "files": files,
                "archive_sha256": _digest(archive)}
    target = archive_dir / "manifest.json"
    fd = os.open(target, os.O_CREAT | os.O_EXCL | os.O_WRONLY, 0o600)
    with os.fdopen(fd, "w", encoding="utf-8") as stream:
        json.dump(manifest, stream, ensure_ascii=False, sort_keys=True)
    validate_bundle(manifest, archive_dir)
    return manifest


def validate_bundle(manifest: dict, archive_dir: Path) -> None:
    if manifest.get("format_version") != 1 or not re.fullmatch(
        r"test_[0-9a-f]{32}", manifest.get("resource_id", "")
    ) or manifest.get("database") != {"host": "127.0.0.1", "port": 5433, "name": "paper_review_test"}:
        raise ValueError("invalid recovery manifest target")
    manifest_path = archive_dir / "manifest.json"
    if (manifest_path.is_symlink() or not manifest_path.is_file()
            or manifest_path.stat().st_size > 2_000_000):
        raise ValueError("manifest file is missing or unsafe")
    try:
        with manifest_path.open(encoding="utf-8") as stream:
            if json.load(stream) != manifest:
                raise ValueError("manifest file differs from in-memory bundle")
    except (UnicodeError, json.JSONDecodeError) as exc:
        raise ValueError("manifest file is invalid") from exc
    archive = archive_dir / "database.dump"
    if archive.is_symlink() or not archive.is_file() or _digest(archive) != manifest.get("archive_sha256"):
        raise ValueError("archive hash mismatch")
    seen = set()
    for item in manifest.get("files", []):
        rel = Path(item["path"])
        if rel.is_absolute() or ".." in rel.parts or not rel.parts or item["path"] in seen:
            raise ValueError("invalid bundle file path")
        seen.add(item["path"])
        path = archive_dir / "files" / rel
        if path.is_symlink() or not path.is_file() or path.stat().st_size != item["size"] or _digest(path) != item["sha256"]:
            raise ValueError("bundle file hash mismatch")
    with DockerPostgres(_test_url()) as client:
        if manifest["resource_id"] not in client.list_archive(archive):
            raise ValueError("archive TOC lacks owned schema")


def restore_owned_resources(owned: OwnedResources, manifest: dict, archive_dir: Path) -> None:
    """Replace only this run's stopped source with its verified same-name bundle."""
    if (manifest.get("resource_id") != owned.schema or manifest.get("schema_oid") != owned.schema_oid
            or manifest.get("storage_root") != str(owned.storage_root)
            or manifest.get("roles") != list(owned.role_oids)):
        raise ValueError("bundle does not belong to these live resources")
    owned.assert_cleanup_stage("schema")
    _check_archive_dir(owned, archive_dir)
    validate_bundle(manifest, archive_dir)
    owned.assert_cleanup_stage("schema")
    engine = create_engine(owned.database_url.replace("+asyncpg", "+psycopg"))
    try:
        with engine.begin() as conn:
            active = conn.execute(text("""
                SELECT count(*) FROM pg_stat_activity
                WHERE datname='paper_review_test' AND usename=ANY(:names)
                  AND pid <> pg_backend_pid()
            """), {"names": list(owned.role_oids)}).scalar_one()
            if active:
                raise ValueError("owned roles still have active connections; stop writes first")
            current_schema = conn.execute(text(
                "SELECT oid, nspowner FROM pg_namespace WHERE nspname=:schema"
            ), {"schema": owned.schema}).one_or_none()
            if current_schema != (owned.schema_oid, owned.role_oids[owned.owner_role]):
                raise ValueError("schema ownership changed")
            _assert_schema_dependencies(conn, owned.schema_oid)
            conn.execute(text(f'DROP SCHEMA "{owned.schema}" CASCADE'))
        owned.schema_oid = None
        if owned.storage_root.is_symlink() or not owned.storage_root.is_dir():
            raise ValueError("storage ownership changed")
        info = owned.storage_root.lstat()
        if (info.st_dev, info.st_ino) != (owned.storage_dev, owned.storage_inode):
            raise ValueError("storage ownership changed")
        shutil.rmtree(owned.storage_root)
        owned.storage_dev = None
        owned.storage_inode = None
        with DockerPostgres(owned.database_url) as client:
            client.restore(archive_dir / "database.dump")
        with engine.connect() as conn:
            restored = conn.execute(text("""
                SELECT n.oid,r.rolname FROM pg_namespace n JOIN pg_roles r ON r.oid=n.nspowner
                WHERE n.nspname=:schema
            """), {"schema": owned.schema}).one_or_none()
        if restored is None or restored[1] != owned.owner_role:
            raise ValueError("restored schema owner differs from bundle")
        owned.schema_oid = restored[0]
        if owned.storage_root.exists() or owned.storage_root.is_symlink():
            raise ValueError("storage restore target was replaced")
        owned.storage_root.mkdir(mode=0o700)
        info = owned.storage_root.lstat()
        owned.storage_dev, owned.storage_inode = info.st_dev, info.st_ino
        for item in manifest["files"]:
            source = archive_dir / "files" / item["path"]
            target = owned.storage_root / item["path"]
            target.parent.mkdir(parents=True, exist_ok=True, mode=0o700)
            fd = os.open(target, os.O_CREAT | os.O_EXCL | os.O_WRONLY, 0o600)
            with source.open("rb") as input_stream, os.fdopen(fd, "wb") as output_stream:
                shutil.copyfileobj(input_stream, output_stream)
        snapshot = _database_snapshot(owned)
        same_revision = snapshot["revision"] == manifest["revision"]
        same_tables = snapshot["tables"] == manifest["tables"]
        same_summaries = snapshot["summaries"] == manifest["summaries"]
        same_references = snapshot["references"] == manifest["references"]
        same_files = _source_files(owned, snapshot["file_rows"]) == manifest["files"]
        if not all((same_revision, same_tables, same_summaries, same_references, same_files)):
            differing_tables = [name for name in manifest["tables"]
                                if snapshot["tables"].get(name) != manifest["tables"][name]]
            differing_fields = {name: [key for key, value in manifest["tables"][name].items()
                                       if snapshot["tables"].get(name, {}).get(key) != value]
                                for name in differing_tables}
            raise ValueError("restored bundle mismatch: "
                             f"revision={same_revision} tables={same_tables} "
                             f"summaries={same_summaries} references={same_references} "
                             f"files={same_files} "
                             f"tables_changed={differing_fields}")
    finally:
        engine.dispose()


async def run_drill() -> dict:
    """Create, recover and verify one entirely new virtual pilot environment."""
    from scripts.acceptance_server import acceptance_environment

    owned: OwnedResources | None = None
    archive_dir: Path | None = None
    archive_identity: tuple[int, int] | None = None
    report: dict = {}

    def guard(stage: str) -> None:
        if owned is not None:
            owned.assert_cleanup_stage(stage)

    async with acceptance_environment("published", cleanup_guard=guard, strict_cleanup=True) as runtime:
        owned = OwnedResources.capture(runtime)
        archive_dir = Path(tempfile.mkdtemp(prefix="paper-review-recovery-bundle-"))
        info = archive_dir.lstat()
        archive_identity = (info.st_dev, info.st_ino)
        try:
            start = time.monotonic()
            manifest = backup_owned_resources(owned, archive_dir)
            report["backup_seconds"] = round(time.monotonic() - start, 3)
            engine = create_engine(owned.database_url.replace("+asyncpg", "+psycopg"))
            try:
                with engine.connect() as conn:
                    before_name = conn.execute(text(
                        f'SELECT display_name FROM "{owned.schema}".users WHERE username=:username'
                    ), {"username": "expert.zhou"}).scalar_one()
                try:
                    with engine.begin() as conn:
                        conn.execute(text(f'CREATE TABLE "{owned.schema}".recovery_failure_probe (id integer)'))
                        raise RuntimeError("injected migration failure")
                except RuntimeError as exc:
                    if str(exc) != "injected migration failure":
                        raise
                with engine.begin() as conn:
                    if conn.execute(text("SELECT to_regclass(:name)"), {
                        "name": f"{owned.schema}.recovery_failure_probe"
                    }).scalar_one() is not None:
                        raise ValueError("failed migration left a table behind")
                    conn.execute(text(f'''
                        UPDATE "{owned.schema}".users SET display_name=:name
                        WHERE username=:username
                    '''), {"name": "演练备份后写入", "username": "expert.zhou"})
            finally:
                engine.dispose()
            await runtime.engine.dispose()
            await runtime.auth_engine.dispose()
            start = time.monotonic()
            restore_owned_resources(owned, manifest, archive_dir)
            report["restore_seconds"] = round(time.monotonic() - start, 3)
            engine = create_engine(owned.database_url.replace("+asyncpg", "+psycopg"))
            try:
                with engine.connect() as conn:
                    after_name = conn.execute(text(
                        f'SELECT display_name FROM "{owned.schema}".users WHERE username=:username'
                    ), {"username": "expert.zhou"}).scalar_one()
            finally:
                engine.dispose()
            if after_name != before_name:
                raise ValueError("backup-time rollback did not restore user data")

            async with AsyncClient(transport=ASGITransport(app=runtime.app), base_url="http://recovery") as client:
                async def login(username: str) -> dict:
                    response = await client.post("/api/v1/auth/login", json={
                        "username": username, "password": runtime.seed_password,
                    })
                    if response.status_code != 200:
                        raise ValueError("restored login failed")
                    return {"Authorization": "Bearer " + response.json()["data"]["access_token"]}

                student = await login("student.lin")
                supervisor = await login("supervisor.zhao")
                expert = await login("expert.zhou")
                outsider = await login("other.student")
                result_url = f"/api/v1/my/theses/{runtime.thesis_id}/published-result"
                for headers in (student, supervisor):
                    response = await client.get(result_url, headers=headers)
                    if response.status_code != 200 or response.json()["data"]["total"] != 80:
                        raise ValueError("restored published result is unavailable")
                if (await client.get(result_url, headers=outsider)).status_code != 404:
                    raise ValueError("restored result leaked across student identities")
                originals = [item for item in manifest["files"] if item["path"].startswith("original/")]
                if len(originals) != 1 or not originals[0]["file_id"]:
                    raise ValueError("recovery fixture lacks one completed original")
                file_url = f"/api/v1/files/{originals[0]['file_id']}/content"
                own_file = await client.get(file_url, headers=student)
                if own_file.status_code != 200 or _digest(archive_dir / "files" / originals[0]["path"]) != hashlib.sha256(own_file.content).hexdigest():
                    raise ValueError("restored student file bytes differ")
                if (await client.get(file_url, headers=expert)).status_code != 404:
                    raise ValueError("expert can read restored original file")
            report["resource_id"] = owned.schema
            report["table_count"] = len(manifest["tables"]) - 1
            report["file_count"] = len(manifest["files"])
            report["rule_version"] = manifest["summaries"][0]["rule_snapshot"]["version"]
        finally:
            if archive_dir is not None:
                if archive_dir.is_symlink() or not archive_dir.is_dir():
                    raise ValueError("bundle directory ownership changed; refusing cleanup")
                info = archive_dir.lstat()
                if (info.st_dev, info.st_ino) != archive_identity:
                    raise ValueError("bundle directory ownership changed; refusing cleanup")
                shutil.rmtree(archive_dir)
    assert owned is not None
    engine = create_engine(owned.database_url.replace("+asyncpg", "+psycopg"))
    try:
        with engine.connect() as conn:
            remaining_schema = conn.execute(text(
                "SELECT count(*) FROM pg_namespace WHERE nspname=:name"
            ), {"name": owned.schema}).scalar_one()
            remaining_roles = conn.execute(text(
                "SELECT count(*) FROM pg_roles WHERE rolname=ANY(:names)"
            ), {"names": list(owned.role_oids)}).scalar_one()
    finally:
        engine.dispose()
    if remaining_schema or remaining_roles or owned.storage_root.exists() or archive_dir.exists():
        raise ValueError("owned drill resources were not completely cleaned")
    return report


def main() -> None:
    report = asyncio.run(run_drill())
    print("local_recovery=PASS")
    print(f"resource_id={report['resource_id']}")
    print(f"backup_seconds={report['backup_seconds']}")
    print(f"restore_seconds={report['restore_seconds']}")
    print(f"tables={report['table_count']} files={report['file_count']} rule={report['rule_version']}")
    print("cleanup=PASS")


if __name__ == "__main__":
    main()
